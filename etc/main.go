package main

import (
	"context"
	"log"

	"github.com/genelet/winter/pzutil"
	"github.com/genelet/winter/ssp"
	_ "github.com/go-sql-driver/mysql"
)

func main() {
	c, err := pzutil.NewConfig("../conf/aofei.json")
	if err != nil {
		panic(err)
	}
	control, err := ssp.NewController(context.Background(), c)
	if err != nil {
		panic(err)
	}
	db := control.DB
	defer db.Close()

	ctx := context.Background()
	err = makeViewsForSlotItem(ctx, db)
	if err != nil {
		log.Printf("makeViewsForSlotItem")
		panic(err)
	}
	err = doCountry(ctx, db)
	if err != nil {
		log.Println("doCountry:", err)
		panic(err)
	}
	err = doState(ctx, db)
	if err != nil {
		log.Println("doState:", err)
		panic(err)
	}
	err = doCity(ctx, db)
	if err != nil {
		log.Println("doCity:", err)
		panic(err)
	}

	err = doChannel(ctx, db)
	if err != nil {
		log.Println("doChannel:", err)
		panic(err)
	}
}

