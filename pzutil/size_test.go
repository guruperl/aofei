package pzutil

import (
	"testing"
)

func TestSize(t *testing.T) {
	samples := [][]uint16{
		{468, 60},
		{728, 90},
		{120, 600},
		{160, 600},
		{300, 600},
		{300, 250},
		{336, 280},
		{300, 100},
		{980, 120},
		{250, 360},
		{180, 500},
		{980, 150},
		{468, 400},
		{930, 180},
		{320, 50},
		{300, 50},
		{300, 300},
		{300, 1050},
		{970, 90},
		{970, 250},
		{1000, 90},
		{320, 80},
		{1000, 1000},
		{640, 480},
		{320, 480},
		{1800, 1000},
		{320, 320},
		{320, 160},
		{980, 240},
		{980, 300},
		{980, 400},
		{970, 310},
		{970, 210},
		{480, 320},
		{768, 1024},
		{480, 280},
		{1000, 300},
		{320, 100},
		{800, 250},
		{200, 600},
	}

	for _, sample := range samples {
		sizeID := GetSizeID(sample[0], sample[1])
		w, h := GetSizes(sizeID)
		if w != sample[0] || h != sample[1] {
			t.Errorf(`"%d":{"w":%d,%d "h":%d,%d "Display":"display_psa", "Click":"click_psa"},`, sizeID, sample[0], w, sample[1], h)
		}
	}
}
